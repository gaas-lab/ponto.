import assert from 'node:assert/strict';
import { saldoDia, saldoMes } from './balance.js';

const cases = [
  [['08:32','12:05','13:06','17:59'],-22], [['08:48','13:28','14:30','18:43'],0],
  [['09:15','13:07','14:07','19:17'],14], [['09:23','13:26','14:28','19:13'],0],
  [['08:38','14:19','15:19','18:29'],0], [['08:44','12:30','13:30','18:00'],-32],
  [['08:17','12:00','13:36','18:44'],0], [['08:14','13:25','14:25*','18:15*'],13],
  [['09:31','13:30','14:30','19:30'],11], [['09:47','14:21','15:21','19:29'],0],
  [['09:49','12:28','13:30','19:42'],0], [['08:15','13:07','14:07','18:06'],0],
  [['08:39','13:25','14:25','18:27'],0], [['09:01','13:27','14:27','18:42'],0],
  [['08:27','13:04','14:07','18:16'],0], [['09:11','13:57','14:57','18:34'],-25],
  [['08:56','12:34','13:24','18:55'],21], [['08:20','13:00','14:00','18:26'],18],
  [['09:05','16:03','17:03','19:00'],0], [['09:12','13:20','14:21','19:05'],0],
  [['09:08','13:10','14:10','18:57'],0],
];

for (const [marks, expected] of cases) assert.equal(saldoDia(marks), expected, marks.join(', '));
assert.equal(saldoDia(['08:00','--:--','13:00','17:00']), 0);
assert.equal(saldoDia(null), 0);
assert.equal(saldoMes(cases.map(([marks]) => marks)), -2);
assert.equal((13 * 60 + 28 - (8 * 60 + 48)) + (18 * 60 + 43 - (14 * 60 + 30)) - 528, 5); // Saldo normal preserva os minutos.
console.log(`OK: ${cases.length + 4} verificações; saldo Aristocrata mensal = ${saldoMes(cases.map(([marks]) => marks))} min`);
